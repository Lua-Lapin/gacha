export function gemstoneTitle(gem, motif) {
  return `${gem}の${motif}`
}

export function parseGemstoneTitle(title) {
  for (const gem of Object.keys(gemstones)) {
    for (const motif of Object.keys(gemstoneMotifs)) {
      if (gemstoneTitle(gem, motif) === title) return { gem, motif }
    }
  }
  throw new Error(`unknown gemstone combination: ${title}`)
}
