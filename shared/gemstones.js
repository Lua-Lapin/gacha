export function gemstoneTitle(gem, motif) {
  return `${gem}の${motif}`
}

export function parseGemstoneTitle(title) {
  for (const gem of Object.keys(gemstones)) {
    for (const motif of Object.keys(gemstoneMotifs)) {
      if (gemstoneTitle(gem, motif) === title) return { gem, motif }
    }
  }
  throw new Error(`unknown gemstone combination: ${title}`)
}

// 旧結果のタイトル形式をそのまま読める。旧仕様で重複があっても各要素を一度ずつ使用済みにする。
export function usedGemstoneParts(titles = []) {
  const gems = new Set()
  const motifs = new Set()
  for (const title of titles) {
    try {
      const { gem, motif } = parseGemstoneTitle(title)
      gems.add(gem)
      motifs.add(motif)
    } catch {
      // 手入力などの未登録タイトルは現在の候補を消費しない。
    }
  }
  return { gems, motifs }
}
